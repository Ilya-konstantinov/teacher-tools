#!/usr/bin/env python3
"""Export generated tickets (JSON) to an A4 LuaLaTeX document."""
import argparse
import json
from dataclasses import replace
from string import Template
from pathlib import Path

from .config import load_settings, settings_for_cli, validate_printing

# Геометрия шаблона A4; пользовательские параметры находятся в config.json.
A4_HEIGHT_MM = 297
SLOT_HEIGHT_EPSILON_MM = 0.01  # Компенсация округления размеров TeX.
LINE_SPACING_FACTOR = 1.2
QUESTION_INDENT_MM = 6
QUESTION_GAP_MM = 2
CONTENT_SIDE_PADDING_MM = 5
HEADER_PADDING_MM = 3
HEADER_LINE_GAP_MM = 1
CUT_DASH_WIDTH_MM = 2
CUT_DASH_GAP_MM = 1.5
CUT_LINE_THICKNESS_PT = 0.2

_ESCAPES = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
            '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}',
            '~': r'\textasciitilde{}', '^': r'\textasciicircum{}',
            'σ': r'\ensuremath{\sigma}', 'δ': r'\ensuremath{\delta}',
            'β': r'\ensuremath{\beta}', 'ⁿ': r'\ensuremath{^{n}}'}


def tex_escape(text):
    """Treat input as plain text, never as executable TeX."""
    if not isinstance(text, str):
        raise ValueError('Question text and labels must be strings')
    return ''.join(_ESCAPES.get(c, ' ' if c.isspace() else c) for c in text)


def export_tex(data, *, tickets_per_page=None, margin_mm=None, font_size=None,
               title=None, institution=None, font=None, settings=None):
    settings = settings if settings is not None else load_settings()
    overrides = dict(tickets_per_page=tickets_per_page, margin_mm=margin_mm,
                     font_size=font_size, title=title, institution=institution, font=font)
    options = validate_printing(replace(settings.printing, **{
        key: value for key, value in overrides.items() if value is not None}))
    tickets_per_page, margin_mm, font_size = options.tickets_per_page, options.margin_mm, options.font_size
    tickets = data.get('tickets') if isinstance(data, dict) else None
    if not isinstance(tickets, list) or not tickets:
        raise ValueError('Input must contain a nonempty tickets list')
    rendered = []
    for ticket in tickets:
        if not isinstance(ticket, dict):
            raise ValueError('Each ticket must be an object')
        number = ticket.get('ticket')
        if isinstance(number, bool) or not isinstance(number, int) or number < 1:
            raise ValueError('Ticket number must be a positive integer')
        questions = ticket.get('questions')
        if not isinstance(questions, list) or not questions:
            raise ValueError(f'Ticket {number} must contain a nonempty list of questions')
        texts = []
        for question in questions:
            if not isinstance(question, dict) or not isinstance(question.get('text'), str) or not question['text'].strip():
                raise ValueError(f'Ticket {number} contains an empty or invalid question')
            texts.append(tex_escape(question['text']))
        paragraphs = [rf'\hangindent={QUESTION_INDENT_MM}mm \hangafter=1 \noindent ' + str(i) + r'.\enspace ' + text + r'\par'
                      for i, text in enumerate(texts, 1)]
        body = '\n' + f'\n\\vskip{QUESTION_GAP_MM}mm\n'.join(paragraphs) + '\n'
        rendered.append(r'\Ticket{' + str(number) + '}{' + body + '}')
    slot_mm = (A4_HEIGHT_MM - 2 * margin_mm) / tickets_per_page - SLOT_HEIGHT_EPSILON_MM
    preamble = Template(r'''% Generated by ticket_tools.py print. Compile with lualatex (or xelatex).
\documentclass[a4paper]{article}
\usepackage{fontspec}
\setmainfont{${FONT}}
\usepackage[russian]{babel}
\usepackage[a4paper,margin=${MARGIN}mm]{geometry}
\pagestyle{empty}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0pt}
\setlength{\topskip}{0pt}
\newcommand{\CutLine}{\hbox to\textwidth{\leaders\hbox{\rule{${CUT_WIDTH}mm}{${CUT_THICKNESS}pt}\hskip${CUT_GAP}mm}\hfill}}
\newcommand{\Ticket}[2]{%
  \nointerlineskip\vbox to ${SLOT}mm{%
    \vskip${HEADER_PADDING}mm
    \hbox to\textwidth{\hfil\small ${INSTITUTION}\hfil}%
    \vskip${HEADER_GAP}mm
    \hbox to\textwidth{\hfil\bfseries ${TITLE}\hfil}%
    \vskip${HEADER_GAP}mm
    \hbox to\textwidth{\hfil\bfseries Билет №\,#1\hfil}%
    \vskip${HEADER_PADDING}mm
    \begingroup
      \leftskip=${SIDE_PADDING}mm \rightskip=${SIDE_PADDING}mm
      #2
    \endgroup
    \vfil
    \CutLine
  }%
}
\begin{document}
\fontsize{${SIZE}}{${LEADING}}\selectfont
''')
    preamble = preamble.substitute(
        FONT=tex_escape(options.font), MARGIN=f'{margin_mm:g}', SLOT=f'{slot_mm:.6f}',
        INSTITUTION=tex_escape(options.institution), TITLE=tex_escape(options.title),
        SIZE=f'{font_size:g}', LEADING=f'{font_size * LINE_SPACING_FACTOR:g}',
        CUT_WIDTH=CUT_DASH_WIDTH_MM, CUT_THICKNESS=CUT_LINE_THICKNESS_PT, CUT_GAP=CUT_DASH_GAP_MM,
        HEADER_PADDING=HEADER_PADDING_MM, HEADER_GAP=HEADER_LINE_GAP_MM, SIDE_PADDING=CONTENT_SIDE_PADDING_MM)
    pages = []
    for start in range(0, len(rendered), tickets_per_page):
        pages.append('\n'.join(rendered[start:start + tickets_per_page]))
    return preamble + '\n\\newpage\n'.join(pages) + '\n\\end{document}\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    settings = settings_for_cli(parser, argv)
    defaults = settings.printing
    parser.add_argument('input', type=Path)
    parser.add_argument('-o', '--output', type=Path, help='Default: input filename with .tex extension')
    parser.add_argument('--tickets-per-page', type=int, default=defaults.tickets_per_page)
    parser.add_argument('--margin-mm', type=float, default=defaults.margin_mm)
    parser.add_argument('--font-size', type=float, default=defaults.font_size)
    parser.add_argument('--title', default=defaults.title)
    parser.add_argument('--institution', default=defaults.institution)
    parser.add_argument('--font', default=defaults.font)
    args = parser.parse_args(argv)
    output = args.output or args.input.with_suffix('.tex')
    if output.resolve() == args.input.resolve():
        parser.error('Output must differ from input')
    try:
        document = export_tex(json.loads(args.input.read_text(encoding='utf-8')),
                              tickets_per_page=args.tickets_per_page, margin_mm=args.margin_mm,
                              font_size=args.font_size, title=args.title,
                              institution=args.institution, font=args.font, settings=settings)
        output.write_text(document, encoding='utf-8')
    except (OSError, ValueError) as exc:
        parser.exit(2, f'Error: {exc}\n')
    print(output)


if __name__ == '__main__':
    main()
